const { Pool } = require('pg');
const seedProducts = require('../data/products-seed');

const databaseUrl = process.env.DATABASE_URL;
const pool = global._jaysDb || new Pool({
  ...(databaseUrl ? { connectionString: databaseUrl } : {}),
  ssl: databaseUrl?.includes('sslmode=require') || process.env.NODE_ENV === 'production'
    ? { rejectUnauthorized: false }
    : undefined,
});
global._jaysDb = pool;

let databaseReady;

async function ensureDatabase() {
  if (!databaseUrl) {
    throw new Error('DATABASE_URL is required to connect to Postgres.');
  }
  if (!databaseReady) {
    databaseReady = (async () => {
      await pool.query(`
  CREATE TABLE IF NOT EXISTS products (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug TEXT UNIQUE NOT NULL,
    name TEXT NOT NULL,
    brand TEXT,
    category TEXT NOT NULL,
    price NUMERIC NOT NULL,
    image TEXT,
    images JSONB NOT NULL DEFAULT '[]'::jsonb,
    icon TEXT,
    short_description TEXT,
    features JSONB NOT NULL DEFAULT '[]'::jsonb,
    sabs_approved BOOLEAN NOT NULL DEFAULT FALSE,
    options JSONB NOT NULL DEFAULT '[]'::jsonb,
    stock INTEGER DEFAULT 0,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
  );

  CREATE TABLE IF NOT EXISTS orders (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stripe_session_id TEXT UNIQUE,
    customer_name TEXT,
    customer_email TEXT,
    shipping_address JSONB NOT NULL DEFAULT '{}'::jsonb,
    items JSONB NOT NULL DEFAULT '[]'::jsonb,
    amount_total NUMERIC NOT NULL,
    currency TEXT NOT NULL,
    status TEXT DEFAULT 'pending',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
  );
      `);

      const { rows: countRows } = await pool.query('SELECT COUNT(*)::int AS count FROM products');
      if (countRows[0].count === 0 && seedProducts.length > 0) {
        for (const row of seedProducts) {
          await pool.query(
            `INSERT INTO products
              (slug, name, brand, category, price, image, images, icon, short_description, features, sabs_approved, options, stock, active)
             VALUES ($1, $2, $3, $4, $5, $6, $7::jsonb, $8, $9, $10::jsonb, $11, $12::jsonb, $13, $14)`,
            [
              row.slug, row.name, row.brand || '', row.category, row.price,
              row.image || null, JSON.stringify(row.images || (row.image ? [row.image] : [])),
              row.icon || null, row.short_description || '', JSON.stringify(row.features || []),
              !!row.sabs_approved, JSON.stringify(row.options || []), row.stock ?? 0,
              row.active !== false,
            ]
          );
        }
      }
    })().catch((error) => {
      databaseReady = null;
      throw error;
    });
  }
  return databaseReady;
}

function safeParse(value) {
  if (!value) return [];
  if (Array.isArray(value)) return value;
  try {
    const parsed = typeof value === 'string' ? JSON.parse(value) : value;
    return Array.isArray(parsed) ? parsed : [];
  } catch (e) {
    return [];
  }
}

// The gallery always leads with the product's primary image, with no duplicates.
function galleryFor(row) {
  const list = safeParse(row.images).map(String).filter(Boolean);
  if (row.image && !list.includes(row.image)) list.unshift(row.image);
  return list;
}

function rowToProduct(row) {
  if (!row) return null;
  return {
    ...row,
    price: Number(row.price),
    features: safeParse(row.features),
    options: safeParse(row.options),
    images: galleryFor(row),
    sabs_approved: row.sabs_approved === true || row.sabs_approved === 1,
    active: row.active === true || row.active === 1,
  };
}

module.exports = {
  db: pool,
  ensureDatabase,
  rowToProduct,
};
